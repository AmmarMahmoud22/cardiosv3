"""Flask-free heart-failure risk model: loading + preprocessing + prediction.

Extracted from ``app.py`` so the exact same pipeline is the single source of
truth for both the Flask ``/predict`` route and the WAT
``predict_heart_failure_risk`` tool. The model artifacts and encoders are loaded
lazily on first use; ``verify_model_files()`` lets the web app preserve its
fail-fast-at-startup behaviour.
"""
from __future__ import annotations

import os

import joblib
import pandas as pd

from safety import attach_disclaimer

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(BASE_DIR, "model")

label_encoder_path = os.path.join(MODEL_DIR, "label_encoders.pkl")
one_hot_encoder_path = os.path.join(MODEL_DIR, "one_hot_encoder.pkl")
scaler_path = os.path.join(MODEL_DIR, "scaler.pkl")
model_path = os.path.join(MODEL_DIR, "heart_failure_model.pkl")
# XGBoost native format (generated by analysis/convert_xgb_model.py). Preferred
# over the legacy pickle because it loads without the XGBoost version-mismatch
# compatibility warning.
model_json_path = os.path.join(MODEL_DIR, "heart_failure_model.json")

# Valid options for the categorical features (also defines AgeCategory ordering).
valid_options = {
    'Smoking': ['Yes', 'No'],
    'AlcoholDrinking': ['Yes', 'No'],
    'Stroke': ['Yes', 'No'],
    'DiffWalking': ['Yes', 'No'],
    'Sex': ['Male', 'Female'],
    'AgeCategory': ['18-24', '25-29', '30-34', '35-39', '40-44', '45-49', '50-54',
                    '55-59', '60-64', '65-69', '70-74', '75-79', '80 or older'],
    'Race': ['White', 'Black', 'Asian', 'American Indian/Alaskan Native', 'Other', 'Hispanic'],
    'Diabetic': ['Yes', 'No', 'No, borderline diabetes', 'Yes (during pregnancy)'],
    'PhysicalActivity': ['Yes', 'No'],
    'GenHealth': ['Very good', 'Fair', 'Good', 'Poor', 'Excellent'],
    'Asthma': ['Yes', 'No'],
    'KidneyDisease': ['Yes', 'No'],
    'SkinCancer': ['Yes', 'No'],
}

# Lazily-loaded artifacts.
label_encoders = None
one_hot_encoder = None
scaler = None
model = None
expected_feature_names = None


def verify_model_files() -> None:
    """Raise FileNotFoundError if any artifact is missing (fail-fast helper)."""
    if not all(os.path.exists(p) for p in
               [model_path, label_encoder_path, one_hot_encoder_path, scaler_path]):
        raise FileNotFoundError(
            "❌ One or more model files are missing! Please check the 'model' directory.")


def load_artifacts() -> None:
    """Load encoders, scaler, and model into module globals (idempotent)."""
    global label_encoders, one_hot_encoder, scaler, model, expected_feature_names
    if model is not None:
        return
    verify_model_files()
    # joblib is the scikit-learn–recommended loader (clearer errors on version
    # mismatch). It reads these plain-pickle artifacts fine.
    label_encoders = joblib.load(label_encoder_path)
    one_hot_encoder = joblib.load(one_hot_encoder_path)
    scaler = joblib.load(scaler_path)
    # Prefer the native XGBoost model (no version-compatibility warning); fall
    # back to the legacy pickle if the converted file is not present.
    if os.path.exists(model_json_path):
        from xgboost import XGBClassifier
        model = XGBClassifier()
        model.load_model(model_json_path)
    else:
        model = joblib.load(model_path)
    expected_feature_names = list(scaler.feature_names_in_)


def predict_risk(data: dict):
    """Run the full preprocessing + prediction pipeline.

    Returns ``(payload, status_code)`` so callers (Flask route / WAT tool) can
    surface validation errors consistently.
    """
    try:
        load_artifacts()
        user_input = pd.DataFrame([data])

        required_columns = list(valid_options.keys()) + ['BMI', 'PhysicalHealth',
                                                          'MentalHealth', 'SleepTime']
        missing_columns = [col for col in required_columns if col not in user_input]
        if missing_columns:
            return {"error": f"Missing columns: {missing_columns}"}, 400

        # Map age category to an ordinal index.
        age_mapping = {age: i for i, age in enumerate(valid_options['AgeCategory'])}
        user_input['AgeCategory'] = user_input['AgeCategory'].map(age_mapping)

        # Label-encode binary/categorical features.
        categorical_columns = ['Smoking', 'AlcoholDrinking', 'Stroke', 'DiffWalking', 'Sex',
                               'PhysicalActivity', 'Asthma', 'KidneyDisease', 'SkinCancer']
        for col in categorical_columns:
            if col in label_encoders:
                user_input[col] = label_encoders[col].transform(user_input[col])

        # One-hot encode nominal features.
        nominal_columns = ['Race', 'Diabetic', 'GenHealth']
        one_hot_encoded = one_hot_encoder.transform(user_input[nominal_columns])
        one_hot_df = pd.DataFrame(
            one_hot_encoded,
            columns=one_hot_encoder.get_feature_names_out(nominal_columns))
        user_input = pd.concat([user_input.drop(nominal_columns, axis=1), one_hot_df], axis=1)

        # Reorder to the training feature order, then scale.
        user_input = user_input.reindex(columns=expected_feature_names, fill_value=0)
        user_input_scaled = scaler.transform(user_input)

        prediction = model.predict(user_input_scaled)
        result = "High cardiac risk profile" if prediction[0] == 1 else "Low cardiac risk profile"
        # Clinical-safety gate: every emitted prediction carries the disclaimer.
        return attach_disclaimer({'HeartFailureRisk': result}), 200
    except Exception as e:  # noqa: BLE001
        # The original /predict route returned the error body with a 200 status;
        # preserved here so the Flask behaviour is unchanged.
        return {'error': str(e)}, 200
