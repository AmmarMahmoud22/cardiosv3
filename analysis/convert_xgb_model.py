"""Convert the legacy pickled XGBoost risk model to XGBoost's native format.

The risk model was trained and pickled with an older XGBoost. Loading that
pickle under XGBoost 3.x prints a compatibility warning:

    WARNING: ... If you are loading a serialized model (like pickle in Python ...)
    or configuration generated by an older version of XGBoost, please export the
    model by calling `Booster.save_model` from that version first ...

This script loads the pickle once (in the current XGBoost) and re-saves it via
the native `save_model` API to `backend/model/heart_failure_model.json`. The app
(`risk_model.load_artifacts`) prefers that native file when present, which loads
cleanly with NO warning. The original pickle is kept as a fallback.

Run (with the project .venv):
    .venv\\Scripts\\python.exe analysis\\convert_xgb_model.py
"""
from __future__ import annotations

import warnings
from pathlib import Path

import joblib
import numpy as np
from xgboost import XGBClassifier

REPO = Path(__file__).resolve().parents[1]
MODEL_DIR = REPO / "backend" / "model"
PKL = MODEL_DIR / "heart_failure_model.pkl"
JSON = MODEL_DIR / "heart_failure_model.json"


def main() -> int:
    if not PKL.exists():
        print(f"pickle not found: {PKL}")
        return 1

    # Load the legacy pickle (this is the step that emits the warning today).
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        model = joblib.load(PKL)
        had_warning = any("xgboost" in str(w.message).lower() or "version" in str(w.message).lower()
                          for w in caught)
    print(f"loaded pickle: {type(model).__name__} | n_features={getattr(model, 'n_features_in_', '?')}")
    print(f"compatibility warning on pickle load: {had_warning}")

    # Re-serialize in the current XGBoost native format.
    model.save_model(str(JSON))
    print(f"saved native model -> {JSON.relative_to(REPO)}")

    # Verify: reload natively (must produce NO warning) and confirm identical predictions.
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        reloaded = XGBClassifier()
        reloaded.load_model(str(JSON))
        native_warning = any("xgboost" in str(w.message).lower() or "version" in str(w.message).lower()
                             for w in caught)
    print(f"compatibility warning on native load: {native_warning}")

    n_feat = int(getattr(model, "n_features_in_", 29))
    rng = np.random.RandomState(0)
    sample = rng.rand(64, n_feat).astype("float32")
    same = np.array_equal(model.predict(sample), reloaded.predict(sample))
    proba_close = np.allclose(model.predict_proba(sample), reloaded.predict_proba(sample), atol=1e-6)
    print(f"predictions identical: {same} | probabilities match: {proba_close}")

    ok = (not native_warning) and same and proba_close
    print("\nRESULT:", "PASS - native model is warning-free and equivalent" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
