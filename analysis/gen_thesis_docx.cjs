function tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const mk = (t, w, o = {}) => new TableCell({
    borders, width: { size: w, type: WidthType.DXA },
    shading: { fill: o.fill || "FFFFFF", type: ShadingType.CLEAR },
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT,
      children: [run(t, { bold: !!o.bold, color: o.color, size: 21 })] })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    visuallyRightToLeft: true,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => mk(h, widths[i], { bold: true, color: "FFFFFF", fill: BLUE })) }),
      ...rows.map((r, ri) => new TableRow({ children: r.map((c, i) => mk(c, widths[i], { fill: ri % 2 ? "F2F6FC" : "FFFFFF" })) })),
    ],
  });
}
