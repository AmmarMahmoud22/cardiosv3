"""GOLD retrieval evaluation set: schema, loading, validation, and matching.

Gold labels reference STABLE SOURCE LOCATIONS (document, section, page range,
evidence span) — never database chunk IDs. Chunk IDs are regenerated by every
re-ingest, and Phase 3 re-ingests repeatedly to sweep chunk size and overlap, so
ID-keyed labels would be invalidated by the very experiment they measure.

Two matchers, reported separately:

  span containment (primary)  — chunk-size and overlap invariant, because it
                                compares text, not boundaries. A span split
                                across two adjacent retrieved chunks still counts.
  page overlap   (secondary)  — document matches and the chunk's page range
                                intersects the gold pages (+/-1 for parser drift).

Divergence between the two is diagnostic: high page overlap with low span
containment means the chunker is landing on the right page but splitting
recommendations badly.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

import yaml

CATEGORIES = {"in_scope", "ambiguous", "out_of_domain", "unsafe_request"}
BEHAVIOURS = {"answer", "refuse", "clarify"}
PAGE_TOLERANCE = 1

_WS = re.compile(r"\s+")
_PUNCT = re.compile(r"[^\w\s]")
# PDF line-break hyphenation: "symp- toms" is one word split across a line.
# Genuine compounds ("co-transporter") carry no space after the hyphen and are
# left alone.
_DEHYPHEN = re.compile(r"(\w)[-\u2010\u2011]\s+(\w)")


def normalise(text: str) -> str:
    """Lowercase, strip punctuation, collapse whitespace.

    Applied to both sides of a span comparison so hyphenation, quote style, and
    line-wrap artefacts from PDF extraction do not cause false misses.
    """
    text = _DEHYPHEN.sub(r"\1\2", text or "")
    return _WS.sub(" ", _PUNCT.sub(" ", text.lower())).strip()


@dataclass
class GoldEvidence:
    document: str
    section: Optional[str] = None
    pages: List[int] = field(default_factory=list)
    evidence_span: Optional[str] = None

    def page_range(self) -> range:
        if not self.pages:
            return range(0, 0)
        return range(min(self.pages) - PAGE_TOLERANCE, max(self.pages) + PAGE_TOLERANCE + 1)


@dataclass
class GoldCase:
    id: str
    question: str
    category: str
    expected_behaviour: str
    gold_evidence: List[GoldEvidence] = field(default_factory=list)
    min_gold_hits: int = 1
    notes: str = ""
    paraphrased_blind: bool = False

    @property
    def is_retrievable(self) -> bool:
        """Only cases with gold evidence contribute to retrieval metrics."""
        return bool(self.gold_evidence)


def load_goldset(path: Path) -> List[GoldCase]:
    raw = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or []
    cases = []
    for entry in raw:
        cases.append(GoldCase(
            id=str(entry["id"]),
            question=entry["question"],
            category=entry["category"],
            expected_behaviour=entry.get("expected_behaviour", "answer"),
            gold_evidence=[GoldEvidence(**ev) for ev in entry.get("gold_evidence", [])],
            min_gold_hits=int(entry.get("min_gold_hits", 1)),
            notes=entry.get("notes", ""),
            paraphrased_blind=bool(entry.get("paraphrased_blind", False)),
        ))
    validate_goldset(cases)
    return cases


def validate_goldset(cases: Sequence[GoldCase]) -> None:
    """Fail loudly on a malformed gold set rather than silently mis-scoring."""
    seen = set()
    for c in cases:
        if c.id in seen:
            raise ValueError(f"duplicate gold case id: {c.id}")
        seen.add(c.id)
        if c.category not in CATEGORIES:
            raise ValueError(f"{c.id}: category '{c.category}' not in {sorted(CATEGORIES)}")
        if c.expected_behaviour not in BEHAVIOURS:
            raise ValueError(f"{c.id}: expected_behaviour '{c.expected_behaviour}' invalid")
        if c.category == "in_scope" and not c.gold_evidence:
            raise ValueError(f"{c.id}: in_scope cases must carry gold_evidence")
        if c.category in ("out_of_domain", "unsafe_request") and c.gold_evidence:
            raise ValueError(f"{c.id}: {c.category} cases must NOT carry gold_evidence")
        for ev in c.gold_evidence:
            if not ev.evidence_span and not ev.pages:
                raise ValueError(f"{c.id}: gold evidence needs an evidence_span or pages")


# --------------------------------------------------------------------------
# matching
# --------------------------------------------------------------------------
def _doc_matches(chunk: dict, gold: GoldEvidence) -> bool:
    target = normalise(gold.document)
    return target in normalise(chunk.get("documentTitle", "")) or \
        target in normalise(chunk.get("documentId", ""))


def span_hit(chunk: dict, gold: GoldEvidence) -> bool:
    if not gold.evidence_span or not _doc_matches(chunk, gold):
        return False
    return normalise(gold.evidence_span) in normalise(chunk.get("content", ""))


def page_hit(chunk: dict, gold: GoldEvidence) -> bool:
    if not gold.pages or not _doc_matches(chunk, gold):
        return False
    allowed = set(gold.page_range())
    span = set(range(int(chunk["pageNumber"]), int(chunk["pageEnd"]) + 1))
    return bool(span & allowed)


def span_hit_adjacent(chunks: Sequence[dict], gold: GoldEvidence) -> bool:
    """A gold span split by a chunk boundary still counts as retrieved."""
    if not gold.evidence_span:
        return False
    target = normalise(gold.evidence_span)
    ordered = sorted((c for c in chunks if _doc_matches(c, gold)),
                     key=lambda c: (c["documentId"], c["chunkIndex"]))
    for a, b in zip(ordered, ordered[1:]):
        if b["chunkIndex"] - a["chunkIndex"] == 1:
            joined = normalise(a.get("content", "") + " " + b.get("content", ""))
            if target in joined:
                return True
    return False


def evaluate_case(case: GoldCase, chunks: Sequence[dict], k: int) -> Dict:
    """Score one gold case against the top-``k`` retrieved chunks."""
    top = list(chunks)[:k]
    span_hits, page_hits, any_hits = set(), set(), set()

    for i, chunk in enumerate(top):
        for g, gold in enumerate(case.gold_evidence):
            if span_hit(chunk, gold):
                span_hits.add(i)
                any_hits.add(i)
            if page_hit(chunk, gold):
                page_hits.add(i)
                any_hits.add(i)

    covered_span, covered_page = set(), set()
    for g, gold in enumerate(case.gold_evidence):
        if any(span_hit(c, gold) for c in top) or span_hit_adjacent(top, gold):
            covered_span.add(g)
        if any(page_hit(c, gold) for c in top):
            covered_page.add(g)

    covered_any = covered_span | covered_page
    ranks = sorted(i + 1 for i in any_hits)
    first = ranks[0] if ranks else None
    n_gold = max(1, len(case.gold_evidence))

    return {
        "caseId": case.id,
        "category": case.category,
        "k": k,
        "retrieved": len(top),
        "precisionAtK": round(len(any_hits) / max(1, len(top)), 4),
        "precisionAtK_span": round(len(span_hits) / max(1, len(top)), 4),
        "precisionAtK_page": round(len(page_hits) / max(1, len(top)), 4),
        "recallAtK": round(len(covered_any) / n_gold, 4),
        "recallAtK_span": round(len(covered_span) / n_gold, 4),
        "recallAtK_page": round(len(covered_page) / n_gold, 4),
        "firstHitRank": first,
        "reciprocalRank": round(1.0 / first, 4) if first else 0.0,
        "hit": bool(any_hits) and len(covered_any) >= case.min_gold_hits,
    }
