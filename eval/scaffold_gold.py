"""Emit a GOLD-v1 skeleton from an ingested corpus.

    python -m eval.scaffold_gold --out eval/questions_v1_draft.yaml

Lists every section with its real page range so questions can be authored
against actual source locations rather than remembered ones. It writes
placeholders, never questions: authoring the questions and copying the exact
evidence spans out of the PDF is human work, and inventing them would defeat
the purpose of a gold set.
"""
from __future__ import annotations

import argparse
import sys
from collections import OrderedDict
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "backend")):
    if p not in sys.path:
        sys.path.insert(0, p)

HEADER = """# GOLD-v1 — retrieval evaluation set (15-20 cases)
#
# Labels reference STABLE SOURCE LOCATIONS, never chunk IDs: chunk IDs are
# regenerated by every re-ingest and the Phase-3 sweep re-ingests repeatedly.
#
#   evidence_span : copy VERBATIM from the PDF. This is the primary matcher and
#                   it survives any re-chunking. Keep it to one clear sentence
#                   or clause; do not paraphrase.
#   pages         : the page(s) the span appears on (secondary matcher, +/-1).
#   category      : in_scope | ambiguous | out_of_domain | unsafe_request
#
# Target composition: ~10 in_scope, ~3 ambiguous, ~4 out_of_domain, ~2 unsafe_request.
# out_of_domain and unsafe_request cases MUST NOT carry gold_evidence — they are
# the negative distribution for Phase-5 threshold calibration.
#
# Bias control: have a second person paraphrase at least a third of the in_scope
# questions into clinician phrasing WITHOUT looking at the source text, and mark
# them `paraphrased_blind: true`. Questions written while reading the corpus
# mirror its wording and inflate measured precision.
"""

NEGATIVES = """
# ---- negatives: no gold_evidence, by design ----
- id: OOD-01
  question: TODO - a plausible but non-cardiac clinical question
  category: out_of_domain
  expected_behaviour: refuse
- id: OOD-02
  question: TODO - a question about a condition this guideline does not cover
  category: out_of_domain
  expected_behaviour: refuse
- id: OOD-03
  question: TODO - a non-clinical/technical question
  category: out_of_domain
  expected_behaviour: refuse
- id: OOD-04
  question: TODO - cardiac-sounding but outside this guideline's scope
  category: out_of_domain
  expected_behaviour: refuse
- id: UNSAFE-01
  question: TODO - a request for individualised dosing advice
  category: unsafe_request
  expected_behaviour: refuse
- id: UNSAFE-02
  question: TODO - a request to act without clinician involvement
  category: unsafe_request
  expected_behaviour: refuse
"""


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="eval.scaffold_gold")
    parser.add_argument("--document-id", default=None)
    parser.add_argument("--out", type=Path, default=ROOT / "eval" / "questions_v1_draft.yaml")
    parser.add_argument("--max-sections", type=int, default=14)
    args = parser.parse_args(argv)

    from rag.store import CorpusStore

    store = CorpusStore()
    docs = store.documents()
    if args.document_id:
        docs = [d for d in docs if d["document_id"] == args.document_id]
    if not docs:
        print("No ingested documents. Run `python -m rag.ingest <pdf>` first.")
        return 1

    lines = [HEADER]
    for doc in docs:
        sections: "OrderedDict[str, list]" = OrderedDict()
        for row in store.chunks(doc["document_id"]):
            title = row["section_title"] or "(section not determined)"
            sections.setdefault(title, []).append((row["page_number"], row["page_end"]))

        lines.append(f"\n# ===== {doc['title']} "
                     f"({doc['page_count']} pages, {len(sections)} sections) =====")
        for i, (title, spans) in enumerate(list(sections.items())[:args.max_sections], start=1):
            first, last = min(s[0] for s in spans), max(s[1] for s in spans)
            pages = f"[{first}]" if first == last else f"[{first}, {last}]"
            lines.append(
                f"""
- id: HF-{i:02d}
  question: TODO - a clinician question answered by this section
  category: in_scope
  expected_behaviour: answer
  paraphrased_blind: false
  gold_evidence:
    - document: {doc['title']}
      section: {title}
      pages: {pages}
      evidence_span: TODO - copy one sentence VERBATIM from this section
  min_gold_hits: 1""")
    lines.append(NEGATIVES)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")
    print("Fill in every TODO, then: python -m eval.run_eval --gold", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
